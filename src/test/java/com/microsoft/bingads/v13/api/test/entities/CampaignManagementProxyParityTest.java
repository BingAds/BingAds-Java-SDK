    @Test
    public void settingsRoundTripThroughBaseSetting() throws JAXBException {
        ImpressionTrackingSetting impression = factory.createImpressionTrackingSetting();
        impression.setImpressionTrackingUrl("https://example.com/track");
        assertEquals("ImpressionTrackingSetting", impression.getType());
        assertEquals(impression.getImpressionTrackingUrl(),
                ((ImpressionTrackingSetting) roundTrip(factory.createSetting(impression),
                        ImpressionTrackingSetting.class)).getImpressionTrackingUrl());

        ReachOptimizationGoalSetting reach = factory.createReachOptimizationGoalSetting();
        reach.setOptimizationGoal(ReachOptimizationGoal.MAX_UNIQUE_REACH);
        assertEquals("ReachOptimizationGoalSetting", reach.getType());
        assertEquals(reach.getOptimizationGoal(),
                ((ReachOptimizationGoalSetting) roundTrip(factory.createSetting(reach),
                        ReachOptimizationGoalSetting.class)).getOptimizationGoal());
        assertEquals("MaxUniqueReach", ReachOptimizationGoal.MAX_UNIQUE_REACH.value());
        assertEquals(ReachOptimizationGoal.MAX_IMPRESSIONS,
                ReachOptimizationGoal.fromValue("MaxImpressions"));

        CampaignFrequencyCapSetting frequency = factory.createCampaignFrequencyCapSetting();
        frequency.setCapValue(5);
        frequency.setTimeGranularity(FrequencyCapTimeGranularity.DAY);
        assertEquals("CampaignFrequencyCapSetting", frequency.getType());
        CampaignFrequencyCapSetting restoredFrequency = (CampaignFrequencyCapSetting) roundTrip(
                factory.createSetting(frequency), CampaignFrequencyCapSetting.class);
        assertEquals(frequency.getCapValue(), restoredFrequency.getCapValue());
        assertEquals(frequency.getTimeGranularity(), restoredFrequency.getTimeGranularity());

        UnifiedAutomationSetting automation = factory.createUnifiedAutomationSetting();
        automation.setAutoGeneratedTextOptOut(true);
        automation.setFinalUrlExpansionOptOut(false);
        assertEquals("UnifiedAutomationSetting", automation.getType());
        UnifiedAutomationSetting restoredAutomation = (UnifiedAutomationSetting) roundTrip(
                factory.createSetting(automation), UnifiedAutomationSetting.class);
        assertEquals(automation.getAutoGeneratedTextOptOut(), restoredAutomation.getAutoGeneratedTextOptOut());
        assertEquals(automation.getFinalUrlExpansionOptOut(), restoredAutomation.getFinalUrlExpansionOptOut());
    }

